#!/usr/bin/env python3
"""
Generates backend/src/main/resources/db/migration/V11__exercise_library_11.sql
from the Android bundle's default_exercises.json (version 11).

Exercise library 10 (V2 + V8) had 60 exercises. Version 11 (Plan 10
step 05a) deprecates 5, changes a few fields on existing ones and adds 9.
This script emits only that delta, parsed from the JSON like
generate_reference_seed.py: no id is ever typed by hand.

    python3 backend/tools/generate_exercise_library_11_seed.py

Deterministic output, so V11's Flyway checksum moves only with its
inputs. Once V11 has run anywhere, never regenerate it: a later
library change gets its own migration.
"""
import json

from generate_reference_seed import (
    EXERCISES_JSON, REPO_ROOT, SEED_UPDATED_AT, exercise_insert, section, sql_bool, sql_str,
)

OUTPUT_SQL = REPO_ROOT / "backend/src/main/resources/db/migration/V11__exercise_library_11.sql"
EXPECTED_VERSION = 11
# Exercises seeded by V2 (library 9/10): the first 60 in the file.
V10_EXERCISE_COUNT = 60
# Existing exercises whose deprecated, difficulty or tracking type
# changed in version 11. Their new values are read from the JSON.
CHANGED = [
    "Tricep Dip", "Upright Row", "Concentration Curl", "Dumbbell Front Raise", "Bicycle Crunch",
    "Push-Up", "Dumbbell Chest Fly", "Hack Squat",
]


def main() -> None:
    data = json.loads(EXERCISES_JSON.read_text())
    assert data["version"] == EXPECTED_VERSION, f"expected library version {EXPECTED_VERSION}, got {data['version']}"
    old = data["exercises"][:V10_EXERCISE_COUNT]
    new = data["exercises"][V10_EXERCISE_COUNT:]
    by_name = {e["name"]: e for e in old}
    changed = [by_name[n] for n in CHANGED]
    deprecated = {e["name"] for e in old if e["deprecated"]}
    assert deprecated <= set(CHANGED), f"deprecated but not in CHANGED: {deprecated - set(CHANGED)}"

    lines = [
        "-- Generated by backend/tools/generate_exercise_library_11_seed.py. Do not hand-edit.",
        f"-- Source: {EXERCISES_JSON.relative_to(REPO_ROOT)} (version {data['version']},",
        f"-- {len(changed)} changed, {len(new)} new exercises). Plan 10 step 05a.",
        "",
        *section("changed exercises"),
    ]
    for e in changed:
        lines += [
            f"UPDATE exercises SET deprecated = {sql_bool(e['deprecated'])}, "
            f"difficulty = {sql_str(e['difficulty'])}, tracking_type = {sql_str(e['trackingType'])}\n"
            f"WHERE source = 'DEFAULT' AND id = {sql_str(e['id'])}; -- {e['name']}",
            "",
        ]
    lines += section("new exercises")
    for e in new:
        lines += [exercise_insert(e), ""]
    lines += [
        *section("reference_version"),
        "-- Clients replace their library when this differs from theirs.",
        f"UPDATE reference_version SET exercise_library_version = {data['version']}, updated_at = {SEED_UPDATED_AT} WHERE id = 1;",
        "",
    ]
    OUTPUT_SQL.write_text("\n".join(lines))
    print(f"Wrote {OUTPUT_SQL.relative_to(REPO_ROOT)}: {len(changed)} changed, {len(new)} new")


if __name__ == "__main__":
    main()
