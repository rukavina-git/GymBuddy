#!/usr/bin/env python3
"""
Generates backend/src/main/resources/db/migration/V7__starter_plans.sql
from the Android bundle's default_workout_templates.json (version 6).

V2 seeded template library version 5. Version 6 (Plan 6 step 06)
deprecates those 13 templates, adds new ones and adds starter plans.
This script emits only that delta, parsed from the JSON like
generate_reference_seed.py: no id is ever typed by hand.

    python3 backend/tools/generate_starter_plans_seed.py

Deterministic output, so V7's Flyway checksum moves only with its
inputs. Once V7 has run anywhere, never regenerate it: a later
library change gets its own migration.
"""
import json
from pathlib import Path

from generate_reference_seed import (
    REPO_ROOT, SEED_UPDATED_AT, TEMPLATES_JSON, section, sql_bool, sql_str, sql_str_or_null,
    template_exercise_insert, template_insert,
)

OUTPUT_SQL = REPO_ROOT / "backend/src/main/resources/db/migration/V7__starter_plans.sql"
EXPECTED_VERSION = 6
# Templates seeded by V2 (library version 5): everything V7 deprecates.
V2_TEMPLATE_COUNT = 13

SCHEMA = """\
-- ============================================================
-- schema
-- ============================================================

-- Starter plans: server-owned reference data, versioned with the
-- template library (template_library_version). Users don't create
-- plans (owner decision 1A); the chosen one is user_profile.active_plan_id.
CREATE TABLE starter_plans (
    id              UUID    NOT NULL PRIMARY KEY,
    title           TEXT    NOT NULL,
    description     TEXT,
    suggested_for   TEXT,
    display_order   INT     NOT NULL,
    deprecated      BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT starter_plans_suggested_for_ck
        CHECK (suggested_for IS NULL OR suggested_for IN ('ONE_TO_THREE', 'FOUR', 'FIVE_TO_SEVEN'))
);

CREATE TABLE starter_plan_templates (
    plan_id         UUID    NOT NULL REFERENCES starter_plans (id) ON DELETE CASCADE,
    template_id     UUID    NOT NULL REFERENCES workout_templates (id),
    order_index     INT     NOT NULL,

    PRIMARY KEY (plan_id, order_index)
);

-- Soft reference to starter_plans.id, not a foreign key: a plan can
-- be deprecated or a client can send an id from a newer library.
ALTER TABLE user_profile ADD COLUMN active_plan_id UUID;
"""


def main() -> None:
    data = json.loads(TEMPLATES_JSON.read_text())
    assert data["version"] == EXPECTED_VERSION, f"expected library version {EXPECTED_VERSION}, got {data['version']}"
    old = data["templates"][:V2_TEMPLATE_COUNT]
    new = data["templates"][V2_TEMPLATE_COUNT:]
    assert all(t["deprecated"] for t in old), "the V2 templates must all be deprecated in version 6"
    plans = data["plans"]

    lines = [
        "-- Generated by backend/tools/generate_starter_plans_seed.py. Do not hand-edit.",
        f"-- Source: {TEMPLATES_JSON.relative_to(REPO_ROOT)} (version {data['version']},",
        f"-- {len(new)} new templates, {len(plans)} plans). Plan 6 step 06.",
        "",
        SCHEMA,
        *section("deprecate the version 5 templates"),
        "UPDATE workout_templates SET deprecated = TRUE",
        "WHERE source = 'DEFAULT' AND id IN (",
        ",\n".join("    " + sql_str(t["id"]) for t in old),
        ");",
        "",
        *section("new templates"),
    ]
    for t in new:
        lines += [template_insert(t), ""]
    for t in new:
        for te in t["exercises"]:
            lines += [template_exercise_insert(t["id"], te), ""]

    lines += [
        *section("starter plans"),
    ]
    for i, p in enumerate(plans):
        lines.append(
            "INSERT INTO starter_plans (id, title, description, suggested_for, display_order, deprecated)\n"
            f"VALUES ({sql_str(p['id'])}, {sql_str(p['title'])}, {sql_str_or_null(p.get('description'))}, "
            f"{sql_str_or_null(p.get('suggestedFor'))}, {i}, {sql_bool(p.get('deprecated', False))});"
        )
        lines.append("")
        for j, tid in enumerate(p["templateIds"]):
            lines.append(
                "INSERT INTO starter_plan_templates (plan_id, template_id, order_index)\n"
                f"VALUES ({sql_str(p['id'])}, {sql_str(tid)}, {j});"
            )
            lines.append("")

    lines += [
        *section("reference_version"),
        f"UPDATE reference_version SET template_library_version = {data['version']}, updated_at = {SEED_UPDATED_AT} WHERE id = 1;",
        "",
    ]
    OUTPUT_SQL.write_text("\n".join(lines))
    print(f"Wrote {OUTPUT_SQL.relative_to(REPO_ROOT)}: {len(new)} templates, {len(plans)} plans")


if __name__ == "__main__":
    main()
