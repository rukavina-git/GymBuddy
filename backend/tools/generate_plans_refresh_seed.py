#!/usr/bin/env python3
"""
Generates backend/src/main/resources/db/migration/V12__plans_refresh.sql
from the Android bundle: default_exercises.json (version 12) and
default_workout_templates.json (version 7).

Plan 10 step 05b. Exercise library 12 renames Chest Dip to Dip and
makes Assisted Pull-Up REPS_ONLY. Template library 7 deprecates the 8
changed starter templates, adds their replacements and points the 3
starter plans (same plan ids) at them. Parsed from the JSON like the
other generators: no id is ever typed by hand.

    python3 backend/tools/generate_plans_refresh_seed.py

Deterministic output. Once V12 has run anywhere, never regenerate it:
a later library change gets its own migration.
"""
import json

from generate_reference_seed import (
    EXERCISES_JSON, REPO_ROOT, SEED_UPDATED_AT, TEMPLATES_JSON, section, sql_jsonb, sql_str,
    sql_str_or_null, template_exercise_insert, template_insert,
)

OUTPUT_SQL = REPO_ROOT / "backend/src/main/resources/db/migration/V12__plans_refresh.sql"
EXERCISE_VERSION = 12
TEMPLATE_VERSION = 7
# Exercises changed in library 12, by their new name. Every text and
# tracking field is rewritten from the JSON.
# Mountain Climber stays REPS_ONLY: set validation and history use the
# exercise's current type, so old reps-only sets would stop validating.
CHANGED_EXERCISES = ["Dip", "Assisted Pull-Up"]
# Templates in the file: 13 from V2 (deprecated by V7), 10 from V7,
# then the ones added in version 7.
V2_TEMPLATE_COUNT = 13
V7_TEMPLATE_COUNT = 23


def main() -> None:
    ex = json.loads(EXERCISES_JSON.read_text())
    tp = json.loads(TEMPLATES_JSON.read_text())
    assert ex["version"] == EXERCISE_VERSION, f"expected exercise library {EXERCISE_VERSION}, got {ex['version']}"
    assert tp["version"] == TEMPLATE_VERSION, f"expected template library {TEMPLATE_VERSION}, got {tp['version']}"

    by_name = {e["name"]: e for e in ex["exercises"]}
    v7 = tp["templates"][V2_TEMPLATE_COUNT:V7_TEMPLATE_COUNT]
    new = tp["templates"][V7_TEMPLATE_COUNT:]
    # Replaced = V7 templates deprecated in version 7; each has a new one with its title.
    replaced = [t for t in v7 if t["deprecated"]]
    new_by_title = {t["title"]: t for t in new}
    assert sorted(t["title"] for t in replaced) == sorted(new_by_title), "replaced and new titles differ"
    plan_ids = {tid for p in tp["plans"] for tid in p["templateIds"]}
    assert all(t["id"] in plan_ids for t in new), "every new template belongs to a plan"
    assert not any(t["id"] in plan_ids for t in replaced), "plans still point at a replaced template"

    lines = [
        "-- Generated by backend/tools/generate_plans_refresh_seed.py. Do not hand-edit.",
        f"-- Source: {EXERCISES_JSON.relative_to(REPO_ROOT)} (version {ex['version']}) and",
        f"-- {TEMPLATES_JSON.relative_to(REPO_ROOT)} (version {tp['version']},",
        f"-- {len(new)} templates replaced). Plan 10 step 05b.",
        "",
        *section("changed exercises"),
    ]
    for n in CHANGED_EXERCISES:
        e = by_name[n]
        lines += [
            f"UPDATE exercises SET name = {sql_str(e['name'])}, description = {sql_str_or_null(e.get('description'))},\n"
            f"    instructions = {sql_jsonb(e['instructions'])}, tips = {sql_jsonb(e['tips'])},\n"
            f"    tracking_type = {sql_str(e['trackingType'])}\n"
            f"WHERE source = 'DEFAULT' AND id = {sql_str(e['id'])};",
            "",
        ]

    lines += [
        *section("deprecate the replaced templates"),
        "UPDATE workout_templates SET deprecated = TRUE",
        "WHERE source = 'DEFAULT' AND id IN (",
        ",\n".join("    " + sql_str(t["id"]) for t in replaced),
        ");",
        "",
        *section("new templates"),
    ]
    for t in new:
        lines += [template_insert(t), ""]
    for t in new:
        for te in t["exercises"]:
            lines += [template_exercise_insert(t["id"], te), ""]

    lines += section("starter plans point at the new templates")
    for t in replaced:
        lines += [
            f"UPDATE starter_plan_templates SET template_id = {sql_str(new_by_title[t['title']]['id'])}\n"
            f"WHERE template_id = {sql_str(t['id'])}; -- {t['title']}",
            "",
        ]

    lines += [
        *section("reference_version"),
        "-- Clients replace their library when these differ from theirs.",
        f"UPDATE reference_version SET exercise_library_version = {ex['version']}, "
        f"template_library_version = {tp['version']}, updated_at = {SEED_UPDATED_AT} WHERE id = 1;",
        "",
    ]
    OUTPUT_SQL.write_text("\n".join(lines))
    print(f"Wrote {OUTPUT_SQL.relative_to(REPO_ROOT)}: {len(CHANGED_EXERCISES)} exercises, {len(new)} templates")


if __name__ == "__main__":
    main()
